-- 0016_session_epoch.sql —— session token 的身份版本（架构文档 §12.7）
--
-- 修复：session token 的载荷只有 `sub`（用户 ID），`AuthService.resolveBearer`
-- 校验签名之后只确认「用户存在且 `status = 'active'`」。删账号再重建同 ID，
-- 旧 token 在整个 `exp` 窗口内继续有效——「删账号」这个撤销动作本身失效，而且
-- 没有任何日志或错误提示。
--
-- 修法是给账号一个**身份版本**：
--
--   - `session_epoch` 是创建账号时生成的随机值；
--   - token 载荷带 `epoch`，校验时要求等于当前行；
--   - 重建账号生成新值 → 旧 token 失效；
--   - 改密码轮换该值 → 已签发的 token 立即失效。
--
-- 随机值不是凭据：它只回答「这个 token 是不是在这个账号的当前生命周期里签发的」。
-- 泄露它拿不到任何权限——签名仍然需要 `auth.sessionSecret`。
--
-- ## 为什么 `NOT NULL` 必须带 `DEFAULT`
--
-- SQLite 的 `ADD COLUMN` 不能给已有行补值，`NOT NULL` 列必须带默认值。而
-- `DEFAULT (lower(hex(randomblob(16))))` 这种**表达式默认值**是 `ALTER TABLE` 不接受
-- 的（只接受常量），所以分两步：先 `DEFAULT ''` 建列，再 `UPDATE` 把存量行回填。
--
-- **空串语义**：空串不等于任何 token 载荷里的 `epoch`（签发时一定是非空随机值），
-- 等于「这个账号的身份版本未知」——所有已签发的 token 都校验失败，强制重新登录。
-- 这是迁移中途失败、或有人手工 `INSERT` 漏了列时的安全降级方向：宁可多一次登录，
-- 不能让旧 token 继续有效。迁移正常跑完之后库里不会有空串行。
--
-- 回填用 `lower(hex(randomblob(16)))`：128 位随机值的 32 位十六进制表示，与
-- `crypto.randomUUID()` 的 36 位 UUID 形状不同（没有连字符）。两者都不被解析，只做
-- 等值比较。
--
-- ## 幂等
--
-- `ALTER TABLE ... ADD COLUMN` 在 SQLite 没有 `IF NOT EXISTS`。迁移框架按
-- `schema_version` 跳过已应用的版本，所以不需要列级幂等；`WHERE session_epoch = ''`
-- 让回填在手工重跑时只补空串行。

ALTER TABLE app_user ADD COLUMN session_epoch TEXT NOT NULL DEFAULT '';

UPDATE app_user SET session_epoch = lower(hex(randomblob(16))) WHERE session_epoch = '';
