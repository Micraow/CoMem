/**
 * MCP 文本出口共用的措辞（架构文档 §13.2）。
 *
 * ## 截断标记只定义一次
 *
 * MCP 的返回是纯文本，没有独立的 `truncated` 字段，所以「这不是全部内容」只能靠
 * 正文末尾一行标记表达。三个出口都会产出它：`list`（递归展开到上限）、`tree`
 * （节点到上限）、`read`（切片的 `offset + limit` 没到末尾）。
 *
 * 调用方（宿主 hook、控制台）是按**这个字符串本身**识别截断的。任何一处改动——
 * 哪怕只有一个标点或一个空格——都会让一个出口的标记静默失效：用户看到的是
 * 「读完了」，实际拿到的是前 N 条。因此这里只保留一份定义，三处 import。
 *
 * 只有一份这件事由 `tests/unit/api/truncated-marker.test.ts` 做结构性断言（扫描
 * `src/**` 里的字符串字面量）。行为测试只能证明「当前三处一致」，挡不住第四份
 * 定义长出来。
 */

/** 输出被截断时追加的独立一行。三个出口逐字共用。 */
export const TRUNCATED_MARKER = '... (truncated)';
